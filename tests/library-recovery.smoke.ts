import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import path from 'node:path';
import { chromium } from 'playwright';
import { createServer } from '../apps/server/src/app.ts';
import { discoverTools, runProcess } from '../packages/media/src/index.ts';

const output = path.resolve('test-output/library-recovery');
await mkdir(output, { recursive: true });
const tools = await discoverTools(), ffmpeg = tools.ffmpeg;
const fixture = path.join(output, 'unsupported-ffv1.mkv');
await runProcess(ffmpeg, ['-y', '-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=size=320x180:rate=10:duration=3', '-c:v', 'ffv1', fixture]);
const token = randomUUID();
const app = await createServer({ dataDir: path.join(output, `service-${Date.now()}`), ownerToken: token, tools });
await app.listen({ host: '127.0.0.1', port: 0 });
const address = app.server.address(); assert(address && typeof address === 'object');
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
const checks: string[] = [], errors: string[] = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(`http://127.0.0.1:${address.port}`);
  await page.getByLabel('Access token').fill(token);
  await page.getByRole('button', { name: 'Connect', exact: true }).click();
  await page.locator('.app-header').getByRole('button', { name: 'Import', exact: true }).click();
  await page.getByLabel('Local media').setInputFiles(fixture);
  await page.getByRole('heading', { name: 'Library', exact: true }).waitFor();
  await page.getByRole('region', { name: 'File imports' }).getByRole('button', { name: 'Dismiss' }).click();
  await page.getByLabel('Search media', { exact: true }).fill('unsupported');
  await page.getByLabel('Show media', { exact: true }).selectOption('sources');
  await page.getByRole('button', { name: /^Ready / }).click();
  const card = page.locator('.media-card').filter({ has: page.getByRole('heading', { name: 'unsupported-ffv1.mkv', exact: true }) });
  await card.getByRole('button', { name: 'Preview', exact: true }).click();
  await card.getByText('This file could not be played.', { exact: false }).waitFor();
  checks.push('A real FFV1 MKV fails browser playback and exposes recovery in its Library row.');
  await card.getByRole('button', { name: 'Retry playback', exact: true }).click();
  await card.getByText('This file could not be played.', { exact: false }).waitFor();
  await page.route('**/api/v1/jobs', async route => {
    if (route.request().method() === 'POST') await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Temporary test outage' }) });
    else await route.continue();
  });
  await card.getByRole('button', { name: 'Make playback copy', exact: true }).click();
  await card.getByRole('alert').filter({ hasText: 'Temporary test outage' }).waitFor();
  await page.unroute('**/api/v1/jobs');
  tools.ffmpeg = path.join(output, 'deliberately-missing-ffmpeg.exe');
  let submits = 0, retries = 0;
  page.on('request', request => {
    if (request.method() !== 'POST') return;
    const pathname = new URL(request.url()).pathname;
    if (pathname === '/api/v1/jobs') submits++;
    if (/\/jobs\/[^/]+\/retry$/.test(pathname)) retries++;
  });
  await card.getByRole('button', { name: 'Make playback copy', exact: true }).evaluate((button: HTMLButtonElement) => { button.click(); button.click(); });
  await card.getByRole('button', { name: 'Retry playback copy', exact: true }).waitFor({ timeout: 30000 });
  assert.equal(submits, 1);
  tools.ffmpeg = ffmpeg;
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: path.join(output, 'mobile-failure.png'), fullPage: true });
  await page.setViewportSize({ width: 1280, height: 900 });
  await card.getByRole('button', { name: 'Retry playback copy', exact: true }).evaluate((button: HTMLButtonElement) => { button.click(); button.click(); });
  await card.getByText('Playing a compatible copy.', { exact: false }).waitFor({ timeout: 60000 });
  assert.equal(retries, 1);
  await card.locator('video').evaluate(async (video: HTMLVideoElement) => { await video.play(); });
  await page.waitForFunction(() => { const video = document.querySelector<HTMLVideoElement>('.library-preview video'); return video && video.currentTime > .1; });
  await card.locator('video').evaluate((video: HTMLVideoElement) => { video.pause(); video.currentTime=1.4; });
  await page.waitForFunction(() => { const video=document.querySelector<HTMLVideoElement>('.library-preview video');return video&&!video.seeking&&Math.abs(video.currentTime-1.4)<.1; });
  checks.push('Submission failure recovers; repeated clicks create one job; a real failed job retries and produces a playable H.264 copy.');
  await card.getByRole('button', { name: 'Play original', exact: true }).click();
  await card.getByText('This file could not be played.', { exact: false }).waitFor();
  await card.getByRole('button', { name: 'Play playback copy', exact: true }).click();
  await card.getByText('Playing a compatible copy.', { exact: false }).waitFor();
  await page.waitForFunction(() => { const video=document.querySelector<HTMLVideoElement>('.library-preview video');return video&&!video.seeking&&Math.abs(video.currentTime-1.4)<.1; });
  await card.getByRole('button', { name: 'Close preview', exact: true }).click();
  await card.getByRole('button', { name: 'Preview', exact: true }).click();
  await card.getByRole('button', { name: 'Play original', exact: true }).waitFor();
  assert.equal(submits, 1);
  checks.push('Original/copy switching and reopening reuse the existing copy without another render.');
  await card.getByRole('button', { name: 'Edit source', exact: true }).click();
  await page.locator('main[data-page="Editor"]').waitFor();
  await page.goBack();
  await page.getByRole('heading', { name: 'Library', exact: true }).waitFor();
  assert.equal(await page.getByLabel('Search media', { exact: true }).inputValue(), 'unsupported');
  assert.equal(await page.getByLabel('Show media', { exact: true }).inputValue(), 'sources');
  assert.equal(await page.getByRole('button', { name: /^Ready / }).getAttribute('aria-pressed'), 'true');
  await page.goForward();
  await page.locator('main[data-page="Editor"]').waitFor();
  await page.getByRole('heading', { name: 'Editor · unsupported-ffv1.mkv', exact: true }).waitFor();
  await page.locator('.app-header').getByRole('button', { name: 'Library', exact: true }).click();
  assert.equal(await page.getByLabel('Search media', { exact: true }).inputValue(), 'unsupported');
  checks.push('Browser Back/Forward restores Library/Editor and selected source; Library navigation preserves all three filters.');
  await page.getByLabel('Search media', { exact: true }).fill('nothing-matches');
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click();
  assert.equal(await page.getByLabel('Search media', { exact: true }).inputValue(), '');
  assert.equal(await page.getByLabel('Show media', { exact: true }).inputValue(), 'all');
  await page.getByLabel('Show media', { exact: true }).selectOption('sources');
  await card.getByRole('button', { name: 'Preview', exact: true }).click();
  await card.getByRole('button', { name: 'Play original', exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true });
  checks.push('Clear filters recovers an empty result; preview recovery fits a 390px viewport.');
  assert.deepEqual(errors, []);
  await writeFile(path.join(output, 'checks.json'), JSON.stringify({ checks, errors }, null, 2));
  console.log(checks.join('\n'));
} finally { tools.ffmpeg = ffmpeg; await browser.close(); await app.close(); }
