import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { createServer } from '../apps/server/src/app.ts';
import { discoverTools, runProcess } from '../packages/media/src/index.ts';

const output = path.resolve('test-output/import-queue');
await mkdir(output, { recursive: true });
const tools = await discoverTools();
await runProcess(tools.ffmpeg, ['-y', '-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=size=320x180:rate=10:duration=3', '-c:v', 'libx264', '-preset', 'ultrafast', path.join(output, 'sample.mp4')]);
await writeFile(path.join(output, 'invalid.mp4'), 'This is not video');
const token = randomUUID();
const app = await createServer({ dataDir: path.join(output, `service-${Date.now()}`), ownerToken: token, tools });
await app.listen({ host: '127.0.0.1', port: 0 });
const address = app.server.address();
assert(address && typeof address === 'object');
const origin = `http://127.0.0.1:${address.port}`;
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
const errors: string[] = [];
page.on('pageerror', error => errors.push(error.message));
const checks: string[] = [];
try {
  await page.goto(origin);
  await page.getByLabel('Access token').fill(token);
  await page.getByRole('button', { name: 'Connect', exact: true }).click();
  await page.locator('.app-header').getByRole('button', { name: 'Import', exact: true }).click();
  const queue = page.getByRole('region', { name: 'File imports' });
  await page.getByLabel('Local media').setInputFiles([path.join(output, 'sample.mp4'), path.join(output, 'invalid.mp4')]);
  await queue.getByText('1 of 2 ready · 1 failed', { exact: true }).waitFor();
  await queue.getByText('File details', { exact: true }).click();
  assert.equal(await queue.getByText('Ready', { exact: true }).count(), 1);
  assert.equal(await queue.getByText('Failed', { exact: true }).count(), 1);
  checks.push('Mixed batch imports valid media and reports invalid file separately.');
  await queue.getByRole('button', { name: 'Retry failed files' }).click();
  await queue.getByText('0 of 1 ready · 1 failed', { exact: true }).waitFor();
  checks.push('Retry submits only the failed file, not successful files.');
  await queue.getByRole('button', { name: 'View Library' }).click();
  await page.getByRole('heading', { name: 'Library', exact: true }).waitFor();
  await queue.getByRole('button', { name: 'Dismiss', exact: true }).click();
  assert.equal(await queue.count(), 0);
  await page.locator('.app-header').getByRole('button', { name: 'Import', exact: true }).click();
  let release!: () => void;
  const blocked = new Promise<void>(resolve => { release = resolve; });
  let uploadCount = 0;
  await page.route('**/api/v1/uploads', async route => { uploadCount++; await blocked; await route.abort().catch(() => {}); });
  await page.getByLabel('Local media').setInputFiles([path.join(output, 'sample.mp4'), path.join(output, 'sample.mp4')]);
  await queue.getByRole('button', { name: 'Stop import' }).waitFor();
  const extraDrop = await page.evaluateHandle(() => {
    const data = new DataTransfer(); data.items.add(new File(['extra'], 'extra.mp4', { type: 'video/mp4' })); return data;
  });
  await page.locator('body').dispatchEvent('drop', { dataTransfer: extraDrop });
  await page.getByText('An import is already running.', { exact: false }).waitFor();
  await page.locator('.app-header').getByRole('button', { name: 'Library', exact: true }).click();
  await queue.getByRole('button', { name: 'Stop import' }).click();
  await queue.getByText('Import stopped', { exact: true }).waitFor();
  release();
  assert.equal(uploadCount, 1);
  checks.push('Queue survives navigation; stopping aborts the current request and skips waiting files.');
  checks.push('Dropping another file during an active batch cannot start a concurrent import.');
  await page.unroute('**/api/v1/uploads');
  await queue.getByRole('button', { name: 'Dismiss', exact: true }).click();
  await page.locator('.app-header').getByRole('button', { name: 'Import', exact: true }).click();
  await page.getByLabel('Local media').setInputFiles(path.join(output, 'sample.mp4'));
  await queue.getByText('1 of 1 ready', { exact: true }).waitFor();
  checks.push('A new successful import works immediately after cancellation.');
  await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  for (const button of await queue.getByRole('button').all()) {
    const bounds = await button.boundingBox(); assert.ok(bounds && bounds.height >= 44);
  }
  await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true });
  checks.push('390px viewport has no horizontal overflow and queue buttons meet 44px height.');
  await queue.getByRole('button', { name: 'Dismiss', exact: true }).click();
  await page.locator('.app-header').getByRole('button', { name: 'Import', exact: true }).click();
  await page.route('**/api/v1/uploads', route => route.abort('connectionreset'));
  await page.getByLabel('Local media').setInputFiles(path.join(output, 'sample.mp4'));
  await queue.getByText('0 of 1 ready · 1 failed', { exact: true }).waitFor();
  await page.unroute('**/api/v1/uploads');
  await queue.getByRole('button', { name: 'Retry failed files' }).press('Enter');
  await queue.getByText('1 of 1 ready', { exact: true }).waitFor();
  checks.push('Interrupted connection reports failure and keyboard retry successfully imports the file.');
  await page.locator('.app-header').getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByLabel('Color theme').selectOption('light');
  const drop = await page.evaluateHandle(data => {
    const transfer = new DataTransfer(); transfer.items.add(new File([new Uint8Array(data)], 'dropped.mp4', { type: 'video/mp4' })); return transfer;
  }, [...await readFile(path.join(output, 'sample.mp4'))]);
  await page.locator('body').dispatchEvent('drop', { dataTransfer: drop });
  await queue.getByText('1 of 1 ready', { exact: true }).waitFor();
  await queue.getByText('File details', { exact: true }).click();
  await queue.getByText('dropped.mp4', { exact: true }).waitFor();
  await page.getByRole('heading', { name: 'Settings', exact: true }).waitFor();
  checks.push('Global drop uses the same queue, completes on Settings without forcing navigation, and supports the white theme.');
  await queue.getByRole('button',{name:'View Library',exact:true}).click();
  await page.getByRole('button',{name:'Edit source',exact:true}).first().click();
  for(const size of [{width:390,height:844},{width:800,height:600}]){
    await page.setViewportSize(size);
    await page.waitForTimeout(150);
    assert(await page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight+1&&document.documentElement.scrollWidth<=innerWidth+1),'Import panel must not overflow compact Editor');
    const panel=await queue.boundingBox();assert(panel&&panel.height<=size.height*.3+1);
    const cut=page.getByRole('navigation',{name:'Editing tools'}).getByRole('button',{name:'Cut',exact:true});
    if(await cut.getAttribute('aria-expanded')!=='true')await cut.click();
    await page.getByRole('button',{name:'Done',exact:true}).click();
    await page.screenshot({path:path.join(output,`editor-import-${size.width}.png`)});
  }
  await queue.getByRole('button',{name:'Dismiss',exact:true}).click();
  assert.equal(await queue.count(),0);
  checks.push('Expanded import details remain bounded at 390x844 and 800x600 without pushing Editor off-screen; Dismiss remains usable.');
  await page.screenshot({ path: path.join(output, 'mobile-light.png'), fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  await writeFile(path.join(output, 'checks.json'), JSON.stringify({ checks, errors }, null, 2));
  console.log(checks.join('\n'));
} finally { await browser.close(); await app.close(); }
