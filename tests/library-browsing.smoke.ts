import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import path from 'node:path';
import { chromium } from 'playwright';
import { createServer } from '../apps/server/src/app.ts';
import { discoverTools, runProcess } from '../packages/media/src/index.ts';

const output=path.resolve('test-output/library-browsing');
await mkdir(output,{recursive:true});
const tools=await discoverTools();
for(const [name,size] of [['small','160x90'],['large','640x360']])await runProcess(tools.ffmpeg,['-y','-v','error','-f','lavfi','-i',`testsrc2=size=${size}:rate=10:duration=2`,'-c:v','libx264','-preset','ultrafast',path.join(output,`${name}.mp4`)]);
const small=await readFile(path.join(output,'small.mp4')),large=await readFile(path.join(output,'large.mp4'));
const token=randomUUID(),app=await createServer({dataDir:path.join(output,`service-${Date.now()}`),ownerToken:token,tools});
await app.listen({host:'127.0.0.1',port:0});const address=app.server.address();assert(address&&typeof address==='object');
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1280,height:800}}),checks:string[]=[],errors:string[]=[];
page.on('pageerror',error=>errors.push(error.message));
const names=['Zeta','Alpha','Clip 10','Clip 2','Delta','Beta'];
const row=(name:string)=>page.locator('.media-card').filter({has:page.getByRole('heading',{name:`${name}.mp4`,exact:true})});
const listed=()=>page.locator('.media-card h3').allTextContents();
try{
  await page.goto(`http://127.0.0.1:${address.port}`);
  await page.getByLabel('Access token').fill(token);await page.getByRole('button',{name:'Connect',exact:true}).click();
  await page.locator('.app-header').getByRole('button',{name:'Import',exact:true}).click();
  await page.getByLabel('Local media').setInputFiles(names.map(name=>({name:`${name}.mp4`,mimeType:'video/mp4',buffer:name==='Zeta'?large:small})));
  await page.getByRole('heading',{name:'Library',exact:true}).waitFor();
  await page.getByRole('region',{name:'File imports'}).getByRole('button',{name:'Dismiss'}).click();
  assert.deepEqual(await listed(),[...names].reverse().map(name=>`${name}.mp4`));
  await page.getByLabel('Sort library').selectOption('oldest');assert.deepEqual(await listed(),names.map(name=>`${name}.mp4`));
  await page.getByLabel('Sort library').selectOption('largest');assert.equal((await listed())[0],'Zeta.mp4');
  await page.getByLabel('Sort library').selectOption('name');assert.deepEqual(await listed(),['Alpha.mp4','Beta.mp4','Clip 2.mp4','Clip 10.mp4','Delta.mp4','Zeta.mp4']);
  checks.push('Newest, oldest, natural filename order, and largest-file sorting match real imported files.');
  await page.getByLabel('Search media',{exact:true}).fill('Clip');await page.getByLabel('Show media',{exact:true}).selectOption('sources');
  await row('Clip 2').getByRole('button',{name:'Preview',exact:true}).click();
  let nav=page.getByRole('group',{name:'Preview navigation'});
  await nav.focus();await page.keyboard.press('ArrowRight');
  await row('Clip 10').getByRole('button',{name:'Close preview',exact:true}).waitFor();
  await page.waitForFunction(()=>document.activeElement?.classList.contains('preview-navigation'));
  assert.equal(await nav.getByRole('button',{name:'Next preview',exact:true}).isDisabled(),true);
  await page.keyboard.press('ArrowRight');assert.equal(await row('Clip 10').locator('video').count(),1);
  for(const [key,name,target] of [['ArrowLeft','Clip 2','search'],['ArrowRight','Clip 10','video']] as const){
    await nav.focus();
    await page.evaluate(()=>{
      const original=requestAnimationFrame,cancel=cancelAnimationFrame,held=new Map<number,FrameRequestCallback>();let next=-1;
      window.requestAnimationFrame=callback=>{const id=next--;held.set(id,callback);return id;};
      window.cancelAnimationFrame=id=>{if(held.has(id))held.delete(id);else cancel(id);};
      (window as any).releasePreviewFocus=()=>{window.requestAnimationFrame=original;window.cancelAnimationFrame=cancel;for(const callback of held.values())callback(performance.now());held.clear();};
    });
    await page.keyboard.press(key);await row(name).getByRole('button',{name:'Close preview',exact:true}).waitFor();
    const focus=target==='search'?page.getByLabel('Search media',{exact:true}):row(name).locator('video');
    await focus.focus();await page.evaluate(()=>(window as any).releasePreviewFocus());
    assert.equal(await focus.evaluate(element=>element===document.activeElement),true,'Deferred preview navigation must not steal newer input/video focus');
    await page.keyboard.press(key==='ArrowLeft'?'ArrowRight':'ArrowLeft');assert.equal(await row(name).locator('video').count(),1);
  }
  checks.push('Held preview focus callbacks cannot steal newer Search or native video focus; arrow keys stay with those controls.');
  await nav.focus();
  await page.keyboard.press('ArrowLeft');await row('Clip 2').getByRole('button',{name:'Close preview',exact:true}).waitFor();
  await page.getByLabel('Search media',{exact:true}).focus();await page.keyboard.press('ArrowRight');
  assert.equal(await row('Clip 2').locator('video').count(),1);
  await row('Clip 2').locator('video').focus();await page.keyboard.press('ArrowRight');
  assert.equal(await row('Clip 2').locator('video').count(),1);
  await nav.focus();await page.keyboard.press('Escape');assert.equal(await page.locator('.library-preview').count(),0);
  assert.equal(await row('Clip 2').getByRole('button',{name:'Preview',exact:true}).evaluate(el=>el===document.activeElement),true);
  checks.push('Preview arrows follow filtered natural sort, stop at boundaries, ignore typing/native video controls, and Escape restores trigger focus.');
  await page.getByLabel('Search media',{exact:true}).fill('');
  await row('Zeta').getByRole('button',{name:'Preview',exact:true}).click();
  const edit=row('Zeta').getByRole('button',{name:'Edit source',exact:true});await edit.scrollIntoViewIfNeeded();
  await page.waitForFunction(()=>scrollY>300);
  const before=await page.evaluate(()=>scrollY);
  await edit.click();await page.locator('main[data-page="Editor"]').waitFor();
  await page.goBack();await page.getByRole('heading',{name:'Library',exact:true}).waitFor();
  await page.waitForFunction(y=>Math.abs(scrollY-y)<5,before);
  assert.equal(await page.getByLabel('Sort library').inputValue(),'name');
  await row('Zeta').getByRole('button',{name:'Close preview',exact:true}).waitFor();
  await page.goForward();await page.locator('main[data-page="Editor"]').waitFor();
  await page.locator('.app-header').getByRole('button',{name:'Library',exact:true}).click();
  await page.waitForFunction(y=>Math.abs(scrollY-y)<5,before);
  checks.push('Browser Back/Forward and Library navigation restore scroll within 5px, open preview, filters, and sorting after editing.');
  await page.getByLabel('Search media',{exact:true}).fill('missing');
  await page.getByRole('heading',{name:'No matching media'}).waitFor();assert.equal(await page.locator('.preview-navigation').count(),0);
  await page.getByRole('button',{name:'Clear filters'}).click();assert.equal(await page.getByLabel('Sort library').inputValue(),'name');
  await page.setViewportSize({width:390,height:844});await page.evaluate(()=>scrollTo(0,0));
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:path.join(output,'mobile-sorting.png')});
  await row('Alpha').getByRole('button',{name:'Preview',exact:true}).click();
  await page.getByRole('button',{name:'Next preview',exact:true}).click();
  await row('Beta').getByRole('button',{name:'Close preview',exact:true}).waitFor();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert.ok((await page.getByRole('group',{name:'Preview navigation'}).boundingBox())!.width>300);
  await page.screenshot({path:path.join(output,'mobile-preview.png')});
  checks.push('Empty filters close hidden previews; Clear filters retains sorting; mobile sort and preview navigation fit 390px.');
  assert.deepEqual(errors,[]);await writeFile(path.join(output,'checks.json'),JSON.stringify({checks,errors},null,2));console.log(checks.join('\n'));
}finally{await browser.close();await app.close();}
